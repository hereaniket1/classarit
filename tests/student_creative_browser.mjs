import { createRequire } from 'node:module';
import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
const require = createRequire(process.env.CLASSARIT_PLAYWRIGHT_PACKAGE || import.meta.url);
const { chromium } = require('playwright');
const browser = await chromium.launch({ headless:true, channel:'chrome' });
try {
  const context = await browser.newContext({ acceptDownloads:true });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await context.route('**/*', async route => {
    const url = new URL(route.request().url());
    if (url.hostname !== 'classarit.test') return route.abort();
    if (url.pathname.startsWith('/api/')) return route.fulfill({ json:{ groups:[], classes:[], tasks:[], sessions:[], has_more:false } });
    const name = url.pathname === '/student/draw' ? 'student-draw' : url.pathname === '/student/puzzle' ? 'student-puzzle' : 'student-classes';
    const file = url.pathname.startsWith('/static/') ? path.join(process.cwd(),'app',url.pathname) : path.join(process.cwd(),'.cache/loading-review',name+'.html');
    await route.fulfill({ body:await fs.readFile(file), contentType:file.endsWith('.js')?'text/javascript':file.endsWith('.css')?'text/css':'text/html' });
  });
  await page.goto('http://classarit.test/student/draw');
  await page.waitForFunction(() => document.querySelector('#add-planner-event')?.disabled === false);
  const canvas = page.locator('#drawing-canvas');
  await page.waitForFunction(() => document.querySelector('#drawing-canvas')?.dataset.tool === 'pen');
  const penCursor = await canvas.evaluate(el => getComputedStyle(el).cursor);
  assert.ok(penCursor.startsWith('url('));
  await page.locator('[data-draw-tool="brush"]').click();
  assert.notEqual(await canvas.evaluate(el => getComputedStyle(el).cursor),penCursor);
  await page.locator('[data-draw-tool="pen"]').click();
  const blank = await canvas.evaluate(el => el.toDataURL());
  const box = await canvas.boundingBox();
  await page.mouse.move(box.x+30,box.y+30); await page.mouse.down();
  await page.mouse.move(box.x+120,box.y+80,{steps:10}); await page.mouse.up();
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('classarit-drawing:owner')||'[]').length === 1);
  assert.notEqual(await canvas.evaluate(el=>el.toDataURL()),blank);
  await page.getByRole('button',{name:'Add Star',exact:true}).click();
  assert.equal(await canvas.evaluate(el => getComputedStyle(el).cursor),'crosshair');
  await canvas.click({position:{x:200,y:200}});
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('classarit-drawing:owner')||'[]').length === 2);
  await page.getByRole('button',{name:'Undo',exact:true}).click();
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('classarit-drawing:owner')||'[]').length === 1);
  await page.getByRole('button',{name:'Redo',exact:true}).click();
  const download = page.waitForEvent('download');
  await page.getByRole('button',{name:'Download PNG'}).click();
  assert.equal((await download).suggestedFilename(),'classarit-drawing.png');
  await page.reload();
  await page.waitForFunction(() => document.querySelector('#draw-undo')?.disabled === true);
  assert.notEqual(await canvas.evaluate(el=>el.toDataURL()),blank);
  await page.getByRole('button',{name:'Add Rectangle',exact:true}).dragTo(canvas,{targetPosition:{x:150,y:150}});
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('classarit-drawing:owner')||'[]').length === 3);
  const beforeErase = await canvas.evaluate(el => el.toDataURL());
  await page.locator('[data-draw-tool="eraser"]').click();
  assert.ok((await canvas.evaluate(el => getComputedStyle(el).cursor)).startsWith('url('));
  assert.notEqual(await canvas.evaluate(el => getComputedStyle(el).cursor),penCursor);
  const paper = await canvas.boundingBox();
  await page.mouse.move(paper.x+40,paper.y+35); await page.mouse.down();
  await page.mouse.move(paper.x+110,paper.y+75,{steps:10}); await page.mouse.up();
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('classarit-drawing:owner')||'[]').length === 4);
  assert.notEqual(await canvas.evaluate(el => el.toDataURL()),beforeErase);
  await page.locator('[data-draw-tool="move"]').click();
  assert.equal(await canvas.evaluate(el => getComputedStyle(el).cursor),'default');
  for (const width of [1440,390]) {
    await page.setViewportSize({width,height:950});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
    if(width===1440) {
      const tools=await page.locator('.draw-tools').boundingBox();
      const paper=await canvas.boundingBox();
      assert.ok(tools.x>=paper.x+paper.width);
    } else {
      await page.locator('.draw-tools').waitFor({state:'hidden'});
      assert.equal(await page.locator('.draw-tools').isVisible(),false);
      await page.locator('#draw-tools-toggle').click();
      await page.locator('[data-draw-tool="pen"]').click();
      assert.equal(await page.locator('#draw-tools-toggle').getAttribute('aria-expanded'),'false');
      await page.locator('.draw-tools').waitFor({state:'hidden'});
    }
    await page.waitForFunction(() => !document.querySelector('[data-action-spinner]'));
    await page.screenshot({path:path.join('.cache/loading-review',`student-draw-${width}.png`),fullPage:true});
  }
  await page.locator('#quick-search-classes').click();
  const search = page.locator('#student-search-popup');
  await search.locator('[name=q]').fill('Piano');
  await search.getByRole('button',{name:'Search classes',exact:true}).click();
  await page.waitForURL('**/student/classes?**');
  assert.equal(new URL(page.url()).searchParams.get('q'),'Piano');
  await page.goto('http://classarit.test/student/puzzle');
  await page.waitForFunction(() => document.querySelector('[data-ttt-cell="0"]')?.disabled === false);
  assert.equal(await page.locator('#snake-panel').isVisible(),true);
  assert.equal(await page.locator('#ttt-panel').isVisible(),false);
  await page.getByRole('tab',{name:'Tic-tac-toe',exact:true}).click();
  assert.equal(await page.locator('#snake-panel').isVisible(),false);
  await page.locator('#ttt-mode').selectOption('friend');
  for (const index of [0,3,1,4,2]) await page.locator(`[data-ttt-cell="${index}"]`).click();
  assert.equal(await page.locator('#ttt-status').textContent(),'X wins! Ready for another round?');
  assert.equal(await page.locator('#ttt-board .is-winning').count(),3);
  await page.locator('#ttt-new').click();
  assert.equal(await page.locator('[data-ttt-cell]:disabled').count(),0);
  await page.locator('#ttt-mode').selectOption('computer');
  await page.locator('[data-ttt-cell="0"]').click();
  await page.waitForFunction(()=>document.querySelectorAll('[data-mark="O"]').length===1);
  await page.getByRole('tab',{name:'Snake',exact:true}).click();
  assert.equal(await page.getByRole('tab',{name:'Snake',exact:true}).getAttribute('aria-selected'),'true');
  await page.getByRole('tab',{name:'Snake',exact:true}).press('ArrowRight');
  assert.equal(await page.locator('#ttt-panel').isVisible(),true);
  await page.getByRole('tab',{name:'Tic-tac-toe',exact:true}).press('ArrowLeft');
  assert.equal(await page.locator('#snake-panel').isVisible(),true);
  await page.locator('#snake-toggle').click();
  await page.locator('#snake-status').getByText('Keep going! Space pauses.').waitFor();
  await page.locator('#snake-canvas').press('Space');
  assert.equal(await page.locator('#snake-toggle').textContent(),'Resume');
  await page.locator('#snake-toggle').click();
  await page.getByRole('tab',{name:'Tic-tac-toe',exact:true}).click();
  assert.equal(await page.locator('#snake-toggle').textContent(),'Resume');
  await page.getByRole('tab',{name:'Snake',exact:true}).click();
  for (const width of [1440,390]) {
    await page.setViewportSize({width,height:950});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
    await page.waitForFunction(() => !document.querySelector('[data-action-spinner]'));
    await page.screenshot({path:path.join('.cache/loading-review',`student-puzzle-${width}.png`),fullPage:true});
  }
  assert.deepEqual(errors,[]);
  console.log('Passed: drawing, shapes, undo/redo, browser draft, PNG, Quick Add search, tic-tac-toe, Snake pause and responsive layouts.');
} finally { await browser.close(); }
